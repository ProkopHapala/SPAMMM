"""
KekuleExtension.py — GUI extension for Kekule bond-order optimization.

Provides UI panel for running the Kekule pi-bond-order optimizer on the current
molecule (from backend or generated by AsciiArtExtension). Supports two-phase
solve (delocalized + localized) with symmetry-breaking noise.

Wired through ExtensionManager as 'kekule' extension.
"""

